#!/usr/bin/env python3
"""Generate ts/src/wordlists.ts from the frozen wordlist resources.

Embeds both lists as frozen string arrays so the TypeScript mirror stays
zero-dependency and runs in Node and browsers alike. Verifies the SHA-256
checksums from SPEC.md before generating; refuses to emit anything on
mismatch. Regenerate only when the frozen resources change (which, per
SPEC.md, means a new algorithm version).
"""

import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESOURCES = ROOT / "src/main/resources/io/github/dakotad74/npubnames"
OUT = ROOT / "ts/src/wordlists.ts"

EXPECTED = {
    "given-names-1024.txt": "53c0d58ead24ee0b632533f5bb4d52e891fce0e540cd9d0e9dc00fcdf174685a",
    "surnames-1024.txt": "3db1448be28e63a2ead8dbb356423675f162a63f0dd6fd85f4fdc8e90d2289c2",
}


def load(name: str) -> list[str]:
    raw = (RESOURCES / name).read_bytes()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != EXPECTED[name]:
        raise SystemExit(f"checksum mismatch for {name}: {actual}")
    words = raw.decode("utf-8").split("\n")
    if words and words[-1] == "":
        words = words[:-1]
    if len(words) != 1024:
        raise SystemExit(f"{name}: expected 1024 words, got {len(words)}")
    return words


def main() -> None:
    given = load("given-names-1024.txt")
    surnames = load("surnames-1024.txt")

    def array(name: str, words: list[str]) -> str:
        # One word per line keeps diffs reviewable.
        items = ",\n".join(f'  "{w}"' for w in words)
        return f"export const {name}: readonly string[] = Object.freeze([\n{items},\n]);"

    content = (
        "// GENERATED by tools/build-ts-wordlists.py from the frozen wordlists — do not edit.\n"
        "// Integrity checksums per SPEC.md; verified again at import time below.\n"
        'import { createHash } from "node:crypto";\n\n'
        + array("GIVEN", given)
        + "\n\n"
        + array("SURNAMES", surnames)
        + "\n\nexport const GIVEN_SHA256 =\n"
        + f'  "{EXPECTED["given-names-1024.txt"]}";\n'
        + "export const SURNAMES_SHA256 =\n"
        + f'  "{EXPECTED["surnames-1024.txt"]}";\n\n'
        + "function verify(list: readonly string[], expected: string, name: string): void {\n"
        + '  const actual = createHash("sha256").update(list.join("\\n") + "\\n", "utf8").digest("hex");\n'
        + '  if (actual !== expected) {\n'
        + '    throw new Error(`wordlist integrity check failed for ${name}: ${actual}`);\n'
        + "  }\n}\n\n"
        + 'verify(GIVEN, GIVEN_SHA256, "given-names-1024.txt");\n'
        + 'verify(SURNAMES, SURNAMES_SHA256, "surnames-1024.txt");\n'
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT} ({len(given)} given, {len(surnames)} surnames)")


if __name__ == "__main__":
    main()
